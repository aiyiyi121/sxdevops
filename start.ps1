param([ValidateSet('postgresql', 'mysql')][string]$Database = 'postgresql')

$ErrorActionPreference = 'Stop'

function Invoke-QuickstartDocker {
    param([string[]]$DockerArguments)

    & docker @DockerArguments
    if ($LASTEXITCODE -ne 0) {
        throw "Docker command failed. Check the error above; application logs: docker compose logs sxdevops"
    }
}

$projectRoot = Split-Path -Parent $MyInvocation.MyCommand.Path
Push-Location -LiteralPath $projectRoot
$previousComposeFile = $env:COMPOSE_FILE
$env:COMPOSE_FILE = if ($Database -eq 'mysql') { 'docker-compose.mysql.yml' } else { 'docker-compose.yml' }
try {
    if (!(Get-Command docker -ErrorAction SilentlyContinue)) {
        throw 'Please install and start Docker Desktop with Docker Compose first.'
    }
    Invoke-QuickstartDocker -DockerArguments @('compose', 'version')
    Invoke-QuickstartDocker -DockerArguments @('info', '--format', '{{.ServerVersion}}') | Out-Null

    $projectName = if ($env:COMPOSE_PROJECT_NAME) {
        $env:COMPOSE_PROJECT_NAME
    } else {
        ((Split-Path -Leaf $projectRoot).ToLowerInvariant() -replace '[^a-z0-9_-]', '') -replace '^[^a-z0-9]+', ''
    }
    $otherDatabase = if ($Database -eq 'mysql') { 'postgres' } else { 'mysql' }
    $otherVolume = if ($Database -eq 'mysql') { 'postgres_data' } else { 'mysql_data' }
    $otherContainer = Invoke-QuickstartDocker -DockerArguments @('container', 'ls', '-aq', '--filter', "name=^/sxdevops-$otherDatabase`$")
    $otherVolumes = Invoke-QuickstartDocker -DockerArguments @('volume', 'ls', '-q', '--filter', "label=com.docker.compose.project=$projectName", '--filter', "label=com.docker.compose.volume=$otherVolume")
    if ($otherContainer -or $otherVolumes) {
        throw "Existing $otherDatabase installation found. Use its original database option (-Database mysql for MySQL); changing engines does not migrate data."
    }

    $envPath = Join-Path $projectRoot '.env'
    if (!(Test-Path -LiteralPath $envPath -PathType Leaf)) {
        $existingContainer = Invoke-QuickstartDocker -DockerArguments @('container', 'ls', '-aq', '--filter', 'name=^/sxdevops-mysql$')
        $existingVolumes = Invoke-QuickstartDocker -DockerArguments @('volume', 'ls', '-q', '--filter', "label=com.docker.compose.project=$projectName", '--filter', 'label=com.docker.compose.volume=mysql_data')
        $existingPostgres = Invoke-QuickstartDocker -DockerArguments @('container', 'ls', '-aq', '--filter', 'name=^/sxdevops-postgres$')
        $existingPgVolumes = Invoke-QuickstartDocker -DockerArguments @('volume', 'ls', '-q', '--filter', "label=com.docker.compose.project=$projectName", '--filter', 'label=com.docker.compose.volume=postgres_data')
        if ($existingContainer -or $existingVolumes -or $existingPostgres -or $existingPgVolumes) {
            throw 'Existing installation found. Restore its original .env before starting; encryption keys must be preserved.'
        }

        $random = [System.Security.Cryptography.RandomNumberGenerator]::Create()
        try {
            $secretBytes = New-Object byte[] 48
            $cmdbBytes = New-Object byte[] 32
            $postgresBytes = New-Object byte[] 24
            $random.GetBytes($secretBytes)
            $random.GetBytes($cmdbBytes)
            $random.GetBytes($postgresBytes)
            $secretKey = [BitConverter]::ToString($secretBytes).Replace('-', '').ToLowerInvariant()
            $cmdbKey = [Convert]::ToBase64String($cmdbBytes).Replace('+', '-').Replace('/', '_')
            $postgresPassword = [BitConverter]::ToString($postgresBytes).Replace('-', '').ToLowerInvariant()
        } finally {
            $random.Dispose()
        }

        $content = "# Generated by start.ps1. Back up this file and keep its values on upgrades.`nSECRET_KEY=$secretKey`nCMDB_PASSWORD_ENCRYPTION_KEY=$cmdbKey`nPOSTGRES_PASSWORD=$postgresPassword`n"
        $stream = [System.IO.File]::Open($envPath, [System.IO.FileMode]::CreateNew, [System.IO.FileAccess]::Write, [System.IO.FileShare]::None)
        try {
            $contentBytes = [System.Text.Encoding]::UTF8.GetBytes($content)
            $stream.Write($contentBytes, 0, $contentBytes.Length)
        } finally {
            $stream.Dispose()
        }
        Write-Host 'Created .env with random keys. Back up this file.'
    } else {
        Write-Host 'Keeping your existing .env values.'
    }

    if ($Database -eq 'postgresql' -and !$env:POSTGRES_PASSWORD -and
            !(Select-String -LiteralPath $envPath -Pattern '^\s*(export\s+)?POSTGRES_PASSWORD\s*=' -Quiet)) {
        $existingPostgres = Invoke-QuickstartDocker -DockerArguments @('container', 'ls', '-aq', '--filter', 'name=^/sxdevops-postgres$')
        $existingPgVolumes = Invoke-QuickstartDocker -DockerArguments @('volume', 'ls', '-q', '--filter', "label=com.docker.compose.project=$projectName", '--filter', 'label=com.docker.compose.volume=postgres_data')
        if ($existingPostgres -or $existingPgVolumes) {
            throw 'Restore the original POSTGRES_PASSWORD for the existing PostgreSQL database; it will not be regenerated.'
        }
        $random = [System.Security.Cryptography.RandomNumberGenerator]::Create()
        try {
            $postgresBytes = New-Object byte[] 24
            $random.GetBytes($postgresBytes)
            $postgresPassword = [BitConverter]::ToString($postgresBytes).Replace('-', '').ToLowerInvariant()
        } finally {
            $random.Dispose()
        }
        [System.IO.File]::AppendAllText($envPath, "`nPOSTGRES_PASSWORD=$postgresPassword`n", (New-Object System.Text.UTF8Encoding($false)))
        Write-Host 'Added a random database password for this fresh PostgreSQL installation.'
    }

    Invoke-QuickstartDocker -DockerArguments @('compose', 'config', '-q')
    Invoke-QuickstartDocker -DockerArguments @('compose', 'up', '-d', '--build')
    Invoke-QuickstartDocker -DockerArguments @('compose', 'exec', 'sxdevops', 'python', 'manage.py', 'quickstart_admin')
    Write-Host 'Ready: http://localhost:8000/login'
} finally {
    $env:COMPOSE_FILE = $previousComposeFile
    Pop-Location
}
