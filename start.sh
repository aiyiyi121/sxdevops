#!/bin/sh
set -eu

project_root=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
cd "$project_root"

database=postgresql
case "${1:-}" in
    --mysql) database=mysql; shift ;;
    '') ;;
    *) echo "Usage: sh start.sh [--mysql]" >&2; exit 1 ;;
esac
[ "$#" -eq 0 ] || { echo "Usage: sh start.sh [--mysql]" >&2; exit 1; }
if [ "$database" = mysql ]; then
    export COMPOSE_FILE=docker-compose.mysql.yml
    other_database=postgres
    other_volume=postgres_data
else
    export COMPOSE_FILE=docker-compose.yml
    other_database=mysql
    other_volume=mysql_data
fi

if ! command -v docker >/dev/null 2>&1; then
    echo "Please install Docker with Docker Compose first." >&2
    exit 1
fi
docker compose version
docker info --format '{{.ServerVersion}}' >/dev/null

project_name=${COMPOSE_PROJECT_NAME:-$(basename "$project_root" | tr '[:upper:]' '[:lower:]' | tr -cd 'a-z0-9_-' | sed 's/^[^a-z0-9]*//')}
other_container=$(docker container ls -aq --filter "name=^/sxdevops-$other_database$")
other_volumes=$(docker volume ls -q --filter "label=com.docker.compose.project=$project_name" --filter "label=com.docker.compose.volume=$other_volume")
if [ -n "$other_container$other_volumes" ]; then
    echo "Existing $other_database installation found. Use its original database option (--mysql for MySQL); changing engines does not migrate data." >&2
    exit 1
fi

if [ ! -f .env ]; then
    existing_container=$(docker container ls -aq --filter 'name=^/sxdevops-mysql$')
    existing_volumes=$(docker volume ls -q --filter "label=com.docker.compose.project=$project_name" --filter 'label=com.docker.compose.volume=mysql_data')
    existing_postgres=$(docker container ls -aq --filter 'name=^/sxdevops-postgres$')
    existing_pg_volumes=$(docker volume ls -q --filter "label=com.docker.compose.project=$project_name" --filter 'label=com.docker.compose.volume=postgres_data')
    if [ -n "$existing_container$existing_volumes$existing_postgres$existing_pg_volumes" ]; then
        echo "Existing installation found. Restore its original .env before starting; encryption keys must be preserved." >&2
        exit 1
    fi

    secret_key=$(od -An -N48 -tx1 /dev/urandom | tr -d ' \n')
    cmdb_key=$(head -c 32 /dev/urandom | base64 | tr '/+' '_-' | tr -d '\r\n')
    postgres_password=$(od -An -N24 -tx1 /dev/urandom | tr -d ' \n')
    if [ "${#secret_key}" -ne 96 ] || [ "${#cmdb_key}" -ne 44 ] || [ "${#postgres_password}" -ne 48 ]; then
        echo "Could not generate encryption keys." >&2
        exit 1
    fi
    (
        umask 077
        set -C
        printf '# Generated by start.sh. Back up this file and keep its values on upgrades.\nSECRET_KEY=%s\nCMDB_PASSWORD_ENCRYPTION_KEY=%s\nPOSTGRES_PASSWORD=%s\n' "$secret_key" "$cmdb_key" "$postgres_password" > .env
    )
    echo "Created .env with random keys. Back up this file."
else
    echo "Keeping your existing .env values."
fi

if [ "$database" = postgresql ] && [ -z "${POSTGRES_PASSWORD:-}" ] && ! grep -Eq '^[[:space:]]*(export[[:space:]]+)?POSTGRES_PASSWORD[[:space:]]*=' .env; then
    existing_postgres=$(docker container ls -aq --filter 'name=^/sxdevops-postgres$')
    existing_pg_volumes=$(docker volume ls -q --filter "label=com.docker.compose.project=$project_name" --filter 'label=com.docker.compose.volume=postgres_data')
    if [ -n "$existing_postgres$existing_pg_volumes" ]; then
        echo "Restore the original POSTGRES_PASSWORD for the existing PostgreSQL database; it will not be regenerated." >&2
        exit 1
    fi
    postgres_password=$(od -An -N24 -tx1 /dev/urandom | tr -d ' \n')
    [ "${#postgres_password}" -eq 48 ] || { echo "Could not generate database password." >&2; exit 1; }
    printf '\nPOSTGRES_PASSWORD=%s\n' "$postgres_password" >> .env
    echo "Added a random database password for this fresh PostgreSQL installation."
fi

docker compose config -q
docker compose up -d --build
docker compose exec sxdevops python manage.py quickstart_admin
echo "Ready: http://localhost:8000/login"
